function load() {
  if (typeof renderNavFooter === 'function') renderNavFooter();
  const kind = document.body.dataset.page;
  if (!kind) return;

  if (kind === 'about') {
    pageShell(aboutPage(DATA.about));
    document.title = "About Us — Dazzlon";
  } else if (kind === 'careers') {
    pageShell(careersPage(DATA.careers));
    document.title = "Careers & Opportunities — Dazzlon";
  } else if (kind === 'contact') {
    pageShell(contactPage(DATA.contact));
    document.title = "Contact Us — Dazzlon";
  } else if (kind === 'services') {
    pageShell(cardsPage(DATA.services));
    document.title = "Enterprise Services — Dazzlon";
  } else if (kind === 'industries') {
    pageShell(cardsPage(DATA.industries));
    document.title = "Industries Served — Dazzlon";
  } else if (kind === 'insights') {
    pageShell(cardsPage(DATA.insights));
    document.title = "Insights & Thought Leadership — Dazzlon";
  } else if (kind.startsWith('service-')) {
    const k = kind.replace('service-', '');
    const serviceData = SERVICES[k] || SERVICES.qa;
    pageShell(serviceDetailPage(serviceData));
    document.title = `${serviceData.shortTitle || serviceData.title} — Dazzlon`;
  } else if (kind.startsWith('technology-')) {
    const k = kind.replace('technology-', '');
    const techData = TECH[k] || TECH.ai;
    pageShell(serviceDetailPage(techData, true));
    document.title = `${techData.shortTitle || techData.title} — Dazzlon`;
  }

  if (typeof initMotionScroll === 'function') {
    initMotionScroll();
  }
}

document.addEventListener('DOMContentLoaded', load);
